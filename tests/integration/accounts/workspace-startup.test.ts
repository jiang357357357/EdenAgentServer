test('managed account workspaces follow copied and moved data roots even while the original workspace exists', async context => {
  const fixture = await workspaceStartupFixture(context)
  const original = path.join(fixture.temporaryRoot, 'original')
  const copied = path.join(fixture.temporaryRoot, 'copied')
  const moved = path.join(fixture.temporaryRoot, 'moved')
  await fixture.start(original)
  const initial = await fixture.connect('account-a')
  const session = await workspaceResult<{ id: string }>(initial, 'session.create', { title: 'portable workspace' })
  const before = await workspaceResult<WorkspaceInfo>(initial, 'workspace.info', { sessionId: session.id })
  assert.equal(before.status, 'ready')
  assert.equal(before.kind, 'managed')
  assert.equal(before.path, realpathSync(path.join(fixture.accountRoot(original, '101'), 'workspace')))
  await writeFile(path.join(before.path, 'identity.txt'), 'copied workspace data')
  await fixture.stop()

  await cp(original, copied, { recursive: true })
  await writeFile(path.join(before.path, 'identity.txt'), 'original must remain untouched')
  await fixture.start(copied)
  const afterCopy = await fixture.connect('account-a')
  const copyInfo = await workspaceResult<WorkspaceInfo>(afterCopy, 'workspace.info', { sessionId: session.id })
  assert.equal(copyInfo.status, 'ready')
  assert.equal(copyInfo.kind, 'managed')
  assert.equal(copyInfo.path, realpathSync(path.join(fixture.accountRoot(copied, '101'), 'workspace')))
  assert.notEqual(copyInfo.path, before.path)
  assert.equal((await workspaceResult<{ content: string }>(afterCopy, 'workspace.read', { sessionId: session.id, path: 'identity.txt' })).content, 'copied workspace data')
  assert.equal((await workspaceResult<{ id: string }>(afterCopy, 'session.read', { sessionId: session.id })).id, session.id)
  await fixture.assertReady()
  await fixture.stop()

  await rename(copied, moved)
  await fixture.start(moved)
  const afterMove = await fixture.connect('account-a')
  const moveInfo = await workspaceResult<WorkspaceInfo>(afterMove, 'workspace.info', { sessionId: session.id })
  assert.equal(moveInfo.status, 'ready')
  assert.equal(moveInfo.kind, 'managed')
  assert.equal(moveInfo.path, realpathSync(path.join(fixture.accountRoot(moved, '101'), 'workspace')))
  assert.equal((await workspaceResult<{ content: string }>(afterMove, 'workspace.read', { sessionId: session.id, path: 'identity.txt' })).content, 'copied workspace data')
  assert.equal(await readFile(path.join(before.path, 'identity.txt'), 'utf8'), 'original must remain untouched')
  await fixture.assertReady()
})

async function assertMissingToolRoots(databasePath: string, missing: string, temporaryRoot: string, sessionId: string) {
  const database = new EdenDatabase(databasePath, 'mon')
  const signal = AbortSignal.timeout(1000)
  try {
    const workspace = new WorkspaceService(database, []).forSession(sessionId)
    const sessions = new SessionRepository(database, 'mon')
    const session = sessions.read(sessionId)
    const permissions = new PermissionService(database, sessions.events)
    const commands = new CommandService(database, [], undefined, { deviceSettingsPath: path.join(temporaryRoot, 'terminal-settings.json') })
    const tools = workspaceTools(workspace, permissions, session.id, session.id, commands)
    const rejectedPath = /workspace|工作区|ENOENT|missing|不存在/i
    assert.throws(() => workspace.root(), rejectedPath)
    assert.throws(() => workspace.commandRoot(), rejectedPath)
    for (const [name, input] of [
      ['read_file', { path: 'must-not-read.txt' }],
      ['write_file', { path: 'must-not-write.txt', content: 'not approved', createOnly: true }],
      ['exec_command', { command: process.platform === 'win32' ? "Write-Output 'must-not-execute'" : "printf 'must-not-execute'" }],
    ] as const) {
      await assert.rejects(Promise.resolve().then(() => tools.find(tool => tool.name === name)!.execute(input, { callId: name, signal })), rejectedPath)
    }
    assert.deepEqual(permissions.list(), [], 'invalid workspace is rejected before any command/write approval')
    assert.equal(existsSync(missing), false, 'invalid selection must not be silently recreated')
  } finally { database.close() }
}

test('missing legacy workspace does not block account startup and requires explicit recovery that survives restart', async context => {
  const fixture = await workspaceStartupFixture(context)
  const dataRoot = path.join(fixture.temporaryRoot, 'data')
  const missingA = path.join(fixture.temporaryRoot, 'removed-portable-installation', 'workspace-a')
  const missingC = path.join(fixture.temporaryRoot, 'removed-portable-installation', 'workspace-c')
  const project = path.join(fixture.temporaryRoot, 'chosen-project')
  await mkdir(project)
  await writeFile(path.join(project, 'project.txt'), 'explicit project selection')
  const databasePath = await fixture.seedLegacy(dataRoot, '101', missingA)
  const databaseC = await fixture.seedLegacy(dataRoot, '303', missingC)
  const [idA] = await fixture.seedSessions(databasePath, [{ 'workspace.root': missingA }])
  const [idC] = await fixture.seedSessions(databaseC, [{ 'workspace.root': missingC }])
  await fixture.start(dataRoot)
  let a = await fixture.connect('account-a')
  const b = await fixture.connect('account-b')
  let c = await fixture.connect('account-c')
  const sessionA = await workspaceResult<{ id: string }>(a, 'session.read', { sessionId: idA! })
  const sessionB = await workspaceResult<{ id: string }>(b, 'session.create', { title: 'healthy account' })
  const sessionC = await workspaceResult<{ id: string }>(c, 'session.read', { sessionId: idC! })
  const missingInfo = await workspaceResult<WorkspaceInfo>(a, 'workspace.info', { sessionId: sessionA.id })
  assert.equal(missingInfo.path, missingA)
  assert.equal(missingInfo.status, 'missing')
  assert.equal(missingInfo.kind, 'external')
  assert.equal((await workspaceResult<WorkspaceInfo>(b, 'workspace.info', { sessionId: sessionB.id })).status, 'ready')
  assert.ok((await workspaceRpc(a, 'workspace.list', { sessionId: sessionA.id, path: '.' })).error)
  assert.ok((await workspaceRpc(a, 'workspace.read', { sessionId: sessionA.id, path: 'project.txt' })).error)
  assert.ok((await workspaceRpc(b, 'session.read', { sessionId: sessionA.id })).error)
  assert.equal((await workspaceResult<{ id: string }>(b, 'session.read', { sessionId: sessionB.id })).id, sessionB.id)
  await fixture.assertReady()
  await fixture.stop()
  await assertMissingToolRoots(databasePath, missingA, fixture.temporaryRoot, sessionA.id)

  await fixture.start(dataRoot)
  a = await fixture.connect('account-a')
  c = await fixture.connect('account-c')
  assert.equal((await workspaceResult<WorkspaceInfo>(a, 'workspace.info', { sessionId: sessionA.id })).path, missingA)
  assert.equal((await workspaceResult<WorkspaceInfo>(a, 'workspace.info', { sessionId: sessionA.id })).status, 'missing')
  await workspaceResult(a, 'workspace.useDefault', { sessionId: sessionA.id })
  await workspaceResult(c, 'workspace.switch', { sessionId: sessionC.id, path: project })
  assert.equal((await workspaceResult<WorkspaceInfo>(a, 'workspace.info', { sessionId: sessionA.id })).kind, 'managed')
  assert.equal((await workspaceResult<WorkspaceInfo>(c, 'workspace.info', { sessionId: sessionC.id })).kind, 'external')
  assert.equal((await workspaceResult<{ content: string }>(c, 'workspace.read', { sessionId: sessionC.id, path: 'project.txt' })).content, 'explicit project selection')
  assert.equal(existsSync(missingA), false)
  assert.equal(existsSync(missingC), false)
  await fixture.stop()

  await fixture.start(dataRoot)
  const restoredA = await fixture.connect('account-a')
  const restoredB = await fixture.connect('account-b')
  const restoredC = await fixture.connect('account-c')
  const aInfo = await workspaceResult<WorkspaceInfo>(restoredA, 'workspace.info', { sessionId: sessionA.id })
  assert.equal(aInfo.status, 'ready')
  assert.equal(aInfo.kind, 'managed')
  assert.equal(aInfo.path, realpathSync(path.join(fixture.accountRoot(dataRoot, '101'), 'workspace')))
  const cInfo = await workspaceResult<WorkspaceInfo>(restoredC, 'workspace.info', { sessionId: sessionC.id })
  assert.equal(cInfo.status, 'ready')
  assert.equal(cInfo.kind, 'external')
  assert.equal(cInfo.path, realpathSync(project))
  assert.notEqual((await workspaceResult<WorkspaceInfo>(restoredB, 'workspace.info', { sessionId: sessionB.id })).path, aInfo.path)
  await fixture.assertReady()
})

test('a file occupying the managed workspace does not block account startup or get overwritten during recovery', async context => {
  const fixture = await workspaceStartupFixture(context)
  const dataRoot = path.join(fixture.temporaryRoot, 'data')
  const accountRoot = fixture.accountRoot(dataRoot, '101')
  const conflictingPath = path.join(accountRoot, 'workspace')
  const project = path.join(fixture.temporaryRoot, 'selected-project')
  await mkdir(accountRoot, { recursive: true })
  await mkdir(project)
  await writeFile(conflictingPath, 'preserve this conflicting file')
  await fixture.start(dataRoot)
  const socket = await fixture.connect('account-a')
  const session = await workspaceResult<{ id: string }>(socket, 'session.create', { title: 'file conflict recovery' })
  const info = await workspaceResult<WorkspaceInfo>(socket, 'workspace.info', { sessionId: session.id })
  assert.equal(info.path, conflictingPath)
  assert.equal(info.kind, 'managed')
  assert.equal(info.status, 'invalid')
  await fixture.assertReady()
  assert.ok((await workspaceRpc(socket, 'workspace.useDefault', { sessionId: session.id })).error)
  await workspaceResult(socket, 'workspace.switch', { sessionId: session.id, path: project })
  const selected = await workspaceResult<WorkspaceInfo>(socket, 'workspace.info', { sessionId: session.id })
  assert.equal(selected.status, 'ready')
  assert.equal(selected.kind, 'external')
  assert.equal(selected.path, realpathSync(project))
  assert.equal(await readFile(conflictingPath, 'utf8'), 'preserve this conflicting file')
  await fixture.stop()
  await fixture.start(dataRoot)
  const restarted = await fixture.connect('account-a')
  assert.equal((await workspaceResult<WorkspaceInfo>(restarted, 'workspace.info', { sessionId: session.id })).path, realpathSync(project))
  assert.equal(await readFile(conflictingPath, 'utf8'), 'preserve this conflicting file')
  await fixture.assertReady()
})

test('a missing managed workspace stays missing after restart until useDefault explicitly recreates it', async context => {
  const fixture = await workspaceStartupFixture(context)
  const dataRoot = path.join(fixture.temporaryRoot, 'data')
  await fixture.start(dataRoot)
  const original = await fixture.connect('account-a')
  const session = await workspaceResult<{ id: string }>(original, 'session.create', { title: 'explicit default recovery' })
  const info = await workspaceResult<WorkspaceInfo>(original, 'workspace.info', { sessionId: session.id })
  assert.equal(info.status, 'ready')
  assert.equal(info.kind, 'managed')
  await writeFile(path.join(info.path, 'retained.txt'), 'retained in moved directory')
  await fixture.stop()
  const retained = path.join(path.dirname(info.path), 'moved-workspace')
  await rename(info.path, retained)
  await fixture.start(dataRoot)
  const restarted = await fixture.connect('account-a')
  const missing = await workspaceResult<WorkspaceInfo>(restarted, 'workspace.info', { sessionId: session.id })
  assert.equal(missing.status, 'missing')
  assert.equal(missing.kind, 'managed')
  assert.equal(missing.path, info.path)
  assert.equal(existsSync(info.path), false, 'startup must not silently recreate an empty managed workspace')
  await fixture.assertReady()
  await workspaceResult(restarted, 'workspace.useDefault', { sessionId: session.id })
  const recovered = await workspaceResult<WorkspaceInfo>(restarted, 'workspace.info', { sessionId: session.id })
  assert.equal(recovered.status, 'ready')
  assert.equal(recovered.kind, 'managed')
  assert.equal(recovered.path, realpathSync(info.path))
  assert.deepEqual((await workspaceResult<{ entries: unknown[] }>(restarted, 'workspace.list', { sessionId: session.id, path: '.' })).entries, [])
  assert.equal(await readFile(path.join(retained, 'retained.txt'), 'utf8'), 'retained in moved directory')
  await fixture.stop()
  await fixture.start(dataRoot)
  const restored = await fixture.connect('account-a')
  assert.equal((await workspaceResult<WorkspaceInfo>(restored, 'workspace.info', { sessionId: session.id })).status, 'ready')
  await fixture.assertReady()
})
